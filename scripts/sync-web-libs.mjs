#!/usr/bin/env node
/**
 * Builds the browser copies of small, dependency-free backend utilities, so the server
 * and the pages share one implementation and one test suite.
 *
 *   node scripts/sync-web-libs.mjs
 *
 * Each source is transpiled with the backend's TypeScript and wrapped so the page gets a
 * global (window.BsDate). The copy records the source's hash; a unit test fails if
 * the source changes without this being run again.
 *
 * It also copies web/css/fonts.css into the reader page's own <style>: a linked
 * stylesheet holds back the first paint by a whole round trip, two seconds on a weak
 * signal, and the reader is the page a traveller opens from a sticker. A unit test
 * fails if the two drift apart.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const require = createRequire(join(ROOT, 'backend/package.json'));
const ts = require('typescript');

const LIBS = [
  { source: 'backend/src/common/utils/bs-date.ts', target: 'web/js/lib/bs-date.js', global: 'BsDate' },
  { source: 'backend/src/common/utils/stops.ts', target: 'web/js/lib/stops.js', global: 'Stops' },
];

for (const lib of LIBS) {
  const source = readFileSync(join(ROOT, lib.source), 'utf8');
  const hash = createHash('sha256').update(source).digest('hex').slice(0, 16);
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019, removeComments: false },
  });
  const wrapped = `/* Generated from ${lib.source} by scripts/sync-web-libs.mjs (source sha256 ${hash}).
   Do not edit: change the source, run the script, and commit both. */
(function (root) {
  var module = { exports: {} };
  var exports = module.exports;
${outputText.replace(/^/gm, '  ')}
  root.${lib.global} = module.exports;
})(typeof self !== 'undefined' ? self : this);
`;
  const target = join(ROOT, lib.target);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, wrapped);
  console.log(`${lib.target}  ←  ${lib.source}`);
}

// The reader's inline copy of the font faces, between the two marker comments.
const FONTS_START = '/* fonts.css:start (generated by scripts/sync-web-libs.mjs) */';
const FONTS_END = '/* fonts.css:end */';
const faces = readFileSync(join(ROOT, 'web/css/fonts.css'), 'utf8').split('\n').filter((l) => l.startsWith('@font-face')).join('\n');
const pagePath = join(ROOT, 'web/index.html');
const page = readFileSync(pagePath, 'utf8');
const start = page.indexOf(FONTS_START);
const end = page.indexOf(FONTS_END);
if (start < 0 || end < start) throw new Error('web/index.html is missing the fonts.css markers');
writeFileSync(pagePath, `${page.slice(0, start + FONTS_START.length)}\n${faces}\n${page.slice(end)}`);
console.log('web/index.html (font faces)  ←  web/css/fonts.css');
